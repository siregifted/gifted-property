ALTER TABLE public."Enquiries"
  ALTER COLUMN property_id DROP NOT NULL;

DROP POLICY IF EXISTS "Allow public enquiry submissions"
  ON public."Enquiries";

CREATE POLICY "Allow public enquiry submissions"
  ON public."Enquiries"
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    char_length(btrim(name)) BETWEEN 2 AND 120
    AND char_length(btrim(phone)) BETWEEN 7 AND 32
    AND char_length(btrim(email)) BETWEEN 3 AND 254
    AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    AND char_length(btrim(property_title)) BETWEEN 1 AND 200
    AND char_length(btrim(property_location)) BETWEEN 1 AND 200
    AND char_length(btrim(message)) BETWEEN 1 AND 4000
  );

GRANT INSERT ON TABLE public."Enquiries" TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public."Enquiries_id_seq" TO anon, authenticated;

CREATE TABLE public."Inspections" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  property_id bigint NULL,
  property_title text NOT NULL
    CHECK (char_length(btrim(property_title)) BETWEEN 1 AND 200),
  property_location text NOT NULL
    CHECK (char_length(btrim(property_location)) BETWEEN 1 AND 200),
  name text NOT NULL
    CHECK (char_length(btrim(name)) BETWEEN 2 AND 120),
  phone text NOT NULL
    CHECK (char_length(btrim(phone)) BETWEEN 7 AND 32),
  email text NOT NULL
    CHECK (
      char_length(btrim(email)) BETWEEN 3 AND 254
      AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
    ),
  inspection_date date NOT NULL,
  preferred_time text NOT NULL
    CHECK (char_length(btrim(preferred_time)) BETWEEN 1 AND 32),
  message text NOT NULL
    CHECK (char_length(btrim(message)) BETWEEN 1 AND 4000)
);

ALTER TABLE public."Inspections" ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public inspection submissions"
  ON public."Inspections"
  FOR INSERT TO anon, authenticated
  WITH CHECK (true);

GRANT INSERT ON TABLE public."Inspections" TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public."Inspections_id_seq" TO anon, authenticated;
