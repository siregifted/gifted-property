-- Gifted Property: approved listing media and verified map metadata.
-- Review in staging before applying to production.

create table if not exists public."PropertyMedia" (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public."Properties"(id) on delete cascade,
  media_url text not null,
  media_type text not null default 'image'
    check (media_type in ('image', 'video')),
  sort_order integer not null default 0,
  is_cover boolean not null default false,
  is_approved boolean not null default false,
  caption text,
  created_at timestamptz not null default now(),
  constraint property_media_https_url check (media_url ~* '^https://')
);

create index if not exists property_media_property_order_idx
  on public."PropertyMedia"(property_id, sort_order);

create unique index if not exists property_media_one_cover_idx
  on public."PropertyMedia"(property_id)
  where is_cover = true;

alter table public."PropertyMedia" enable row level security;

drop policy if exists "Public can read approved media for published properties"
  on public."PropertyMedia";
create policy "Public can read approved media for published properties"
  on public."PropertyMedia"
  for select
  to anon, authenticated
  using (
    is_approved = true
    and exists (
      select 1
      from public."Properties" p
      where p.id = "PropertyMedia".property_id
        and p.is_published = true
    )
  );

revoke insert, update, delete on public."PropertyMedia" from anon, authenticated;
grant select on public."PropertyMedia" to anon, authenticated;

alter table public."Properties"
  add column if not exists latitude double precision,
  add column if not exists longitude double precision,
  add column if not exists location_verification_status text not null default 'unverified',
  add column if not exists nearby_landmarks text[] not null default '{}';

alter table public."Properties"
  drop constraint if exists properties_latitude_range;
alter table public."Properties"
  add constraint properties_latitude_range
  check (latitude is null or latitude between -90 and 90);

alter table public."Properties"
  drop constraint if exists properties_longitude_range;
alter table public."Properties"
  add constraint properties_longitude_range
  check (longitude is null or longitude between -180 and 180);

alter table public."Properties"
  drop constraint if exists properties_location_verification_status_check;
alter table public."Properties"
  add constraint properties_location_verification_status_check
  check (location_verification_status in ('unverified', 'approximate', 'verified'));

-- Coordinates are deliberately nullable: do not fabricate coordinates for existing listings.
